c=P.calcul('artisan',P.catalogue('artisan').modules.map(m=>m.id));
ok('tout coché : brut 38 €, total plafonné à 25 €',c.brut===3800&&c.total===2500&&c.plafonne);
c=P.calcul('artisan',P.CATALOGUE.artisan.raccourcis[1].modules);
ok('raccourci Artisan pro = tous les modules = 25 €',c.total===2500);
c=P.calcul('artisan',P.CATALOGUE.artisan.raccourcis[0].modules,true);
ok('fondateur : -30 % à vie sur 15 € = 10,50 €',c.total===1050&&c.remise===450);
c=P.calcul('artisan',P.catalogue('artisan').modules.map(m=>m.id),true);
ok('fondateur : -30 % appliqué après le plafond (17,50 €)',c.total===1750);
c=P.calcul('artisan',[]);ok('rien coché : 0 €',c.total===0&&c.lignes.length===0);
ok('ids inconnus, doublons et types étranges ignorés',JSON.stringify(P.nettoyer('artisan',['devis','devis','__proto__',7,null,'3d']))==='["devis","3d"]'&&P.nettoyer('artisan','devis').length===0);
c=P.calcul('bricoleur',P.CATALOGUE.bricoleur.raccourcis[0].modules);
ok('Bricoleur pro : 4 modules = 17 € plafonnés à 10 € TTC',c.brut===1700&&c.total===1000&&c.unite==='TTC');
ok('le plafond ne dépasse jamais le prix des anciennes offres',P.CATALOGUE.artisan.plafond===2500&&P.CATALOGUE.bricoleur.plafond===1000);
const somme=m=>P.CATALOGUE[m].modules.reduce((s,x)=>s+x.prix,0);
ok('aucun module gratuit ou négatif ; total brut au-dessus du plafond (le plafond sert)',Object.keys(P.CATALOGUE).every(m=>P.CATALOGUE[m].modules.every(x=>x.prix>0)&&somme(m)>P.CATALOGUE[m].plafond));
ok('peut() : lit la liste du compte',P.peut({modules:['devis']},'devis')&&!P.peut({modules:['devis']},'paiement')&&!P.peut(null,'devis')&&!P.peut({},'devis'));
ok('euros()',P.euros(1500)==='15 €'&&P.euros(1050)==='10,50 €'&&P.euros(0)==='0 €');
console.log(R.join('\n'));if(R.some(x=>x.startsWith('FAIL')))process.exit(1);
